import Foundation
import SwiftSIMDMathTestSupport

// MARK: - MPFR-Certified Exact Bit-Pattern Golden Corpus Emitter (Dispatch & Unary Slices)

public enum MPFRGoldenCorpusEmitter: Sendable {
    static let maxOpsPerGeneratedFile = 12
    static let maxTopWorstPointsPerOp = MPFRRegimeWorstTracker.defaultCapacity

    public static func emitGoldenCorpus(
        to directoryPath: String,
        scorecardsByOperationName: [String: MPFRAuditOperationScorecard]
    ) throws {
        let dirURL = URL(fileURLWithPath: directoryPath, isDirectory: true)
        let files = Self.renderAllGoldenFiles(scorecardsByOperationName: scorecardsByOperationName)
        let emittedNames = Set(files.map(\.fileName))

        if let existing = try? FileManager.default.contentsOfDirectory(atPath: dirURL.path) {
            for name in existing
            where name.hasPrefix("SIMDMPFRGoldenVectors+") && name.hasSuffix(".swift") && !emittedNames.contains(name) {
                try? FileManager.default.removeItem(at: dirURL.appendingPathComponent(name))
            }
        }

        for (name, contents) in files {
            try contents.write(to: dirURL.appendingPathComponent(name), atomically: true, encoding: .utf8)
        }
    }

    /// Compile-time exhaustive golden file renderer across every `SIMDOperationCategory` (zero `default:` branches).
    static func renderAllGoldenFiles(
        scorecardsByOperationName: [String: MPFRAuditOperationScorecard]
    ) -> [(fileName: String, contents: String)] {
        var files: [(fileName: String, contents: String)] = [
            ("SIMDMPFRGoldenVectors.swift", Self.renderDispatchFile())
        ]
        for category in SIMDOperationCategory.allCases {
            switch category {
            case .unary:
                let unaryGroups = Self.partitionUnaryOperations(SIMDUnaryOperation.allCases)
                for group in unaryGroups where !group.operations.isEmpty {
                    let stem = group.fileName.replacingOccurrences(of: ".swift", with: "")
                    let blocks = group.operations.map { op in
                        Self.renderUnaryOperationBlock(op, scorecard: scorecardsByOperationName[op.rawValue])
                    }
                    files.append(
                        contentsOf: Self.packBlocksIntoFiles(
                            blocks: blocks, baseFileStem: stem, title: group.title, typeName: "SIMDUnaryOperation"
                        )
                    )
                }

            case .binary:
                files.append(contentsOf: Self.renderBinaryFiles(scorecards: scorecardsByOperationName))

            case .ternary:
                files.append(contentsOf: Self.renderTernaryFiles(scorecards: scorecardsByOperationName))

            case .dualUnary:
                files.append(contentsOf: Self.renderDualUnaryFiles(scorecards: scorecardsByOperationName))
            }
        }
        return files
    }

    private static func renderDispatchFile() -> String {
        var lines: [String] = [
            "import SwiftSIMDMathTestSupport",
            "",
            "// MARK: - Compile-Time Exhaustive MPFR Golden Vector Dispatch (Zero default: Branches)",
            "// Generated by Tools/MPFRAudit against GNU MPFR. Adding any new operation forces golden vectors here."
        ]
        for category in SIMDOperationCategory.allCases {
            lines.append("")
            switch category {
            case .unary:
                lines.append(
                    contentsOf: Self.renderDispatchBlock(
                        typeName: "SIMDUnaryOperation",
                        vectorType: "UnaryGoldenVector",
                        docComment:
                            "/// Compile-time exhaustive MPFR-certified golden vectors (zero `default:` branches).",
                        names: SIMDUnaryOperation.allCases.map(\.rawValue)
                    )
                )

            case .binary:
                lines.append(
                    contentsOf: Self.renderDispatchBlock(
                        typeName: "SIMDBinaryOperation",
                        vectorType: "BinaryGoldenVector",
                        docComment:
                            "/// Compile-time exhaustive MPFR-certified golden vectors (zero `default:` branches).",
                        names: SIMDBinaryOperation.allCases.map(\.rawValue)
                    )
                )

            case .ternary:
                lines.append(
                    contentsOf: Self.renderDispatchBlock(
                        typeName: "SIMDTernaryOperation",
                        vectorType: "TernaryGoldenVector",
                        docComment: "/// Compile-time exhaustive exact golden vectors (zero `default:` branches).",
                        names: SIMDTernaryOperation.allCases.map(\.rawValue)
                    )
                )

            case .dualUnary:
                lines.append(
                    contentsOf: Self.renderDispatchBlock(
                        typeName: "SIMDDualUnaryOperation",
                        vectorType: "DualUnaryGoldenVector",
                        docComment:
                            "/// Compile-time exhaustive MPFR-certified golden vectors (zero `default:` branches).",
                        names: SIMDDualUnaryOperation.allCases.map(\.rawValue)
                    )
                )
            }
        }
        return lines.joined(separator: "\n") + "\n"
    }

    private static func renderDispatchBlock(
        typeName: String,
        vectorType: String,
        docComment: String,
        names: [String]
    ) -> [String] {
        var lines: [String] = [
            "extension \(typeName) {",
            "    \(docComment)",
            "    var mpfrGoldenVectors: [\(vectorType)] {",
            "        switch self {"
        ]
        for name in names {
            lines.append("        case .\(name): Self.\(name)GoldenVectors")
        }
        lines.append(contentsOf: ["        }", "    }", "}"])
        return lines
    }

    private static func renderUnaryOperationBlock(
        _ op: SIMDUnaryOperation,
        scorecard: MPFRAuditOperationScorecard?
    ) -> [String] {
        let profile = op.mpfrAuditProfile
        let entries = Self.collectScalarEntries(
            anchors: profile.goldenAnchors, scorecard: scorecard
        )
        var lines: [String] = ["    static let \(op.rawValue)GoldenVectors: [UnaryGoldenVector] = ["]
        for (idx, item) in entries.enumerated() {
            let ref = profile.referenceEvaluator(item.value)
            let comma = idx + 1 == entries.count ? "" : ","
            lines.append("        UnaryGoldenVector(")
            lines.append(
                "            inputBits: \(Self.swiftHex(item.value.bitPattern)), "
                    + "expectedBits: \(Self.swiftHex(ref.bitPattern)), "
                    + "maxULP: \(profile.maxULP), label: \"\(item.label)\")\(comma)"
            )
        }
        lines.append("    ]")
        return lines
    }

    static func collectScalarEntries(
        anchors: [Double],
        scorecard: MPFRAuditOperationScorecard?
    ) -> [(value: Double, label: String)] {
        var seen: Set<UInt64> = []
        var entries: [(value: Double, label: String)] = []
        for (idx, val) in Self.deduplicateDoubles(anchors).enumerated() {
            seen.insert(val.bitPattern)
            entries.append((val, "anchor-\(idx)"))
        }
        if let card = scorecard {
            let candidates =
                card.topWorstInputBitPatterns.isEmpty
                ? (card.worstInputBitPatterns.count == 1 ? [card.worstInputBitPatterns] : [])
                : card.topWorstInputBitPatterns
            var worstIdx = 0
            for tuple in candidates where tuple.count == 1 && worstIdx < Self.maxTopWorstPointsPerOp {
                let bits = tuple[0]
                if seen.insert(bits).inserted {
                    entries.append((Double(bitPattern: bits), "worst-\(worstIdx)"))
                    worstIdx += 1
                }
            }
        }
        return entries
    }

    static func deduplicateDoubles(_ values: [Double]) -> [Double] {
        var seen: Set<UInt64> = []
        var unique: [Double] = []
        for val in values where seen.insert(val.bitPattern).inserted { unique.append(val) }
        return unique
    }

    static func swiftHex(_ bits: UInt64) -> String {
        let raw = String(bits, radix: 16, uppercase: true)
        let pad = String(repeating: "0", count: Swift.max(0, 16 - raw.count)) + raw
        let chars = Array(pad)
        return "0x\(String(chars[0..<4]))_\(String(chars[4..<8]))_\(String(chars[8..<12]))_\(String(chars[12..<16]))"
    }
}
